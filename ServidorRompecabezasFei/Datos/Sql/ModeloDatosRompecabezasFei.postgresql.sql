-- --------------------------------------------------
-- Script de base de datos de RompecabezasFEI para PostgreSQL 12 o superior
-- Equivalente a ModeloDatosRompecabezasFei.edmx.sql (SQL Server)
-- --------------------------------------------------
--
-- Antes de ejecutar este script, crea la base de datos y el usuario
-- (una sola vez, conectado como superusuario, por ejemplo "postgres"):
--
--   CREATE USER rompecabezas WITH PASSWORD 'cambia_esta_contrasena';
--   CREATE DATABASE rompecabezasfei OWNER rompecabezas;
--
-- Después ejecuta este script dentro de esa base de datos:
--
--   psql -U rompecabezas -d rompecabezasfei -f ModeloDatosRompecabezasFei.postgresql.sql
--
-- IMPORTANTE: igual que el script de SQL Server, este script BORRA las
-- tablas si ya existen. No lo ejecutes sobre una base con datos que
-- quieras conservar.
--
-- Notas sobre la traducción desde SQL Server:
--   * Los nombres van entre comillas dobles ("Jugador") porque Entity
--     Framework con Npgsql los busca respetando mayúsculas y minúsculas.
--   * int IDENTITY(1,1)  ->  integer GENERATED BY DEFAULT AS IDENTITY
--   * nvarchar(n)        ->  varchar(n)   (en PostgreSQL todo texto es Unicode)
--   * nchar(n)           ->  char(n)
--   * bit                ->  boolean
--   * El esquema "dbo" de SQL Server se reemplaza por "public".
--   * SQL Server compara textos SIN distinguir mayúsculas y minúsculas
--     ("Beto" = "beto"). PostgreSQL sí las distingue. Para conservar el
--     comportamiento original en el nombre de jugador y el correo, esas
--     columnas usan la intercalación "sin_mayusculas" que se crea abajo.
-- --------------------------------------------------

BEGIN;

-- --------------------------------------------------
-- Borrando las tablas existentes (CASCADE elimina también sus llaves foráneas)
-- --------------------------------------------------

DROP TABLE IF EXISTS "ResultadoPartida" CASCADE;
DROP TABLE IF EXISTS "Partida" CASCADE;
DROP TABLE IF EXISTS "Sala" CASCADE;
DROP TABLE IF EXISTS "Amistad" CASCADE;
DROP TABLE IF EXISTS "SolicitudAmistad" CASCADE;
DROP TABLE IF EXISTS "Cuenta" CASCADE;
DROP TABLE IF EXISTS "Jugador" CASCADE;

-- --------------------------------------------------
-- Intercalación que compara sin distinguir mayúsculas y minúsculas,
-- pero sí acentos (equivalente a la intercalación *_CI_AS de SQL Server)
-- --------------------------------------------------

CREATE COLLATION IF NOT EXISTS sin_mayusculas (
    provider = icu,
    locale = 'und-u-ks-level2',
    deterministic = false
);

-- --------------------------------------------------
-- Creando las tablas
-- --------------------------------------------------

CREATE TABLE "Jugador" (
    "IdJugador" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "NombreJugador" varchar(15) COLLATE sin_mayusculas NOT NULL,
    "NumeroAvatar" integer NOT NULL
);

CREATE TABLE "Cuenta" (
    "IdCuenta" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "Correo" varchar(65) COLLATE sin_mayusculas NOT NULL,
    "Contrasena" char(128) NOT NULL,
    "Jugador_IdJugador" integer NOT NULL
);

CREATE TABLE "SolicitudAmistad" (
    "IdJugadorOrigen" integer NOT NULL,
    "IdJugadorDestino" integer NOT NULL
);

CREATE TABLE "Amistad" (
    "IdJugadorA" integer NOT NULL,
    "IdJugadorB" integer NOT NULL
);

CREATE TABLE "Sala" (
    "IdSala" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "Codigo" varchar(36) NOT NULL,
    "MaximoJugadores" integer NOT NULL,
    "MinimoJugadores" integer NOT NULL
);

CREATE TABLE "Partida" (
    "IdPartida" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "IdSala" integer NOT NULL,
    "Dificultad" integer NOT NULL
);

CREATE TABLE "ResultadoPartida" (
    "IdJugador" integer NOT NULL,
    "IdPartida" integer NOT NULL,
    "Puntaje" integer NOT NULL DEFAULT 0,
    "EsGanador" boolean NOT NULL DEFAULT false
);

-- --------------------------------------------------
-- Llaves primarias
-- --------------------------------------------------

ALTER TABLE "Cuenta"
    ADD CONSTRAINT "PK_Cuenta" PRIMARY KEY ("IdCuenta");

ALTER TABLE "Jugador"
    ADD CONSTRAINT "PK_Jugador" PRIMARY KEY ("IdJugador");

ALTER TABLE "SolicitudAmistad"
    ADD CONSTRAINT "PK_SolicitudAmistad" PRIMARY KEY ("IdJugadorOrigen", "IdJugadorDestino");

ALTER TABLE "Amistad"
    ADD CONSTRAINT "PK_Amistad" PRIMARY KEY ("IdJugadorA", "IdJugadorB");

ALTER TABLE "Sala"
    ADD CONSTRAINT "PK_Sala" PRIMARY KEY ("IdSala");

ALTER TABLE "ResultadoPartida"
    ADD CONSTRAINT "PK_ResultadoPartida" PRIMARY KEY ("IdJugador", "IdPartida");

ALTER TABLE "Partida"
    ADD CONSTRAINT "PK_Partida" PRIMARY KEY ("IdPartida");

-- --------------------------------------------------
-- Llaves foráneas e índices
-- (PostgreSQL no crea índices para las llaves foráneas automáticamente,
-- así que se crean los mismos que en el script de SQL Server)
-- --------------------------------------------------

ALTER TABLE "Cuenta"
    ADD CONSTRAINT "FK_CuentaJugador"
    FOREIGN KEY ("Jugador_IdJugador") REFERENCES "Jugador" ("IdJugador")
    ON DELETE NO ACTION ON UPDATE NO ACTION;

CREATE INDEX "IX_FK_CuentaJugador" ON "Cuenta" ("Jugador_IdJugador");

ALTER TABLE "SolicitudAmistad"
    ADD CONSTRAINT "FK_JugadorSolicitudAmistad"
    FOREIGN KEY ("IdJugadorOrigen") REFERENCES "Jugador" ("IdJugador")
    ON DELETE NO ACTION ON UPDATE NO ACTION;

ALTER TABLE "SolicitudAmistad"
    ADD CONSTRAINT "FK_JugadorSolicitudAmistad1"
    FOREIGN KEY ("IdJugadorDestino") REFERENCES "Jugador" ("IdJugador")
    ON DELETE NO ACTION ON UPDATE NO ACTION;

CREATE INDEX "IX_FK_JugadorSolicitudAmistad1" ON "SolicitudAmistad" ("IdJugadorDestino");

ALTER TABLE "Amistad"
    ADD CONSTRAINT "FK_JugadorAmistad"
    FOREIGN KEY ("IdJugadorA") REFERENCES "Jugador" ("IdJugador")
    ON DELETE NO ACTION ON UPDATE NO ACTION;

ALTER TABLE "Amistad"
    ADD CONSTRAINT "FK_JugadorAmistad1"
    FOREIGN KEY ("IdJugadorB") REFERENCES "Jugador" ("IdJugador")
    ON DELETE NO ACTION ON UPDATE NO ACTION;

CREATE INDEX "IX_FK_JugadorAmistad1" ON "Amistad" ("IdJugadorB");

ALTER TABLE "ResultadoPartida"
    ADD CONSTRAINT "FK_JugadorResultadoPartida"
    FOREIGN KEY ("IdJugador") REFERENCES "Jugador" ("IdJugador")
    ON DELETE NO ACTION ON UPDATE NO ACTION;

ALTER TABLE "Partida"
    ADD CONSTRAINT "FK_SalaPartida"
    FOREIGN KEY ("IdSala") REFERENCES "Sala" ("IdSala")
    ON DELETE NO ACTION ON UPDATE NO ACTION;

CREATE INDEX "IX_FK_SalaPartida" ON "Partida" ("IdSala");

ALTER TABLE "ResultadoPartida"
    ADD CONSTRAINT "FK_PartidaResultadoPartida"
    FOREIGN KEY ("IdPartida") REFERENCES "Partida" ("IdPartida")
    ON DELETE NO ACTION ON UPDATE NO ACTION;

CREATE INDEX "IX_FK_PartidaResultadoPartida" ON "ResultadoPartida" ("IdPartida");

COMMIT;

-- --------------------------------------------------
-- Fin del script
-- --------------------------------------------------
